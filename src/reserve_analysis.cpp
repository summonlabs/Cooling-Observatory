ReserveReport analyse_reserve(const AnalysisContext& context, const QueryFilter& filter) {
  ReserveReport out;
  out.generation = context.state().generation;
  out.epoch = context.state().epoch;
  out.revision = context.state().revision;
  out.as_of_ms = context.now_ms;
  out.dimension = Dimension::Flow;

  const std::vector<DeliveryPoint> points = delivery_points(context);
  std::vector<DeliveryObservation> observations;
  observations.reserve(points.size());
  for (const DeliveryPoint& point : points) {
    observations.push_back(observe_delivery_point(context, point, filter));
  }

  const std::vector<CapabilityEntry> pool = capability_pool(context);

  // Measured delivery attributed to one loop: the sum of the flows of the
  // points that depend on it. A point without a current flow contributes
  // nothing to the sum and marks the sum as not fully evidenced.
  struct Sum {
    std::int64_t total = 0;
    bool any = false;
    bool overflow = false;
    std::vector<Freshness> freshness;
  };

  for (const Loop& loop : context.structure().loops()) {
    if (filter.loop.has_value() && loop.id != filter.loop.value()) {
      continue;
    }
    const SubjectRef scope(SubjectKind::Loop, rebind<StrongId>(loop.id));
    const std::vector<StrongId> served = points_served_by(context, scope, points);
    Sum sum;
    for (std::size_t i = 0; i < points.size(); ++i) {
      if (std::find(served.begin(), served.end(), points[i].id) == served.end()) {
        continue;
      }
      if (!observations[i].flow.value.has_value()) {
        continue;
      }
      const std::optional<std::int64_t> next =
          checked_add(sum.total, observations[i].flow.value.value().value);
      if (!next.has_value()) {
        sum.overflow = true;
        break;
      }
      sum.total = next.value();
      sum.any = true;
      sum.freshness.push_back(observations[i].flow.freshness);
    }

    Maybe<Quantity> delivered;
    Freshness delivered_freshness = Freshness::Unknown;
    if (sum.any && !sum.overflow) {
      delivered = Maybe<Quantity>::of(Quantity(Dimension::Flow, sum.total));
      delivered_freshness = fold_worst_of(sum.freshness);
    }

    const std::vector<const CapabilityEntry*> entries =
        entries_in_loop(pool, context.structure(), loop.id);
    ReserveObservation observation =
        observe_scope(context, scope, entries, delivered, observations, points, filter);
    if (delivered.has_value()) {
      observation.delivered.freshness = delivered_freshness;
    }
    if (sum.overflow) {
      Indeterminacy indeterminacy;
      indeterminacy.code = Code::LimitExceeded;
      indeterminacy.reason = "loop_delivery_out_of_range";
      indeterminacy.detail = "the summed measured delivery of this loop does not fit a signed 64-bit flow";
      observation.indeterminacies.push_back(std::move(indeterminacy));
    }
    if (filter.require_evidenced && observation.basis != ReserveBasis::Evidenced &&
        observation.basis != ReserveBasis::Mixed) {
      continue;
    }
    out.scopes.push_back(std::move(observation));
  }

  // A plant-scope figure, when a plant was named: it is the sum over the loops
  // the plant contains, and it is reported separately from the loops so that a
  // consumer never has to add scope figures together itself.
  if (filter.plant.has_value()) {
    const SubjectRef scope(SubjectKind::Plant, rebind<StrongId>(filter.plant.value()));
    std::vector<const CapabilityEntry*> entries;
    for (const Loop& loop : context.structure().loops()) {
      if (loop.plant != filter.plant.value()) {
        continue;
      }
      const std::vector<const CapabilityEntry*> in_loop = entries_in_loop(pool, context.structure(), loop.id);
      entries.insert(entries.end(), in_loop.begin(), in_loop.end());
    }
    Sum sum;
    for (std::size_t i = 0; i < points.size(); ++i) {
      if (!observations[i].flow.value.has_value()) {
        continue;
      }
      const std::optional<std::int64_t> next = checked_add(sum.total, observations[i].flow.value.value().value);
      if (!next.has_value()) {
        sum.overflow = true;
        break;
      }
      sum.total = next.value();
      sum.any = true;
      sum.freshness.push_back(observations[i].flow.freshness);
    }
    Maybe<Quantity> delivered;
    if (sum.any && !sum.overflow) {
      delivered = Maybe<Quantity>::of(Quantity(Dimension::Flow, sum.total));
    }
    ReserveObservation observation =
        observe_scope(context, scope, entries, delivered, observations, points, filter);
    if (delivered.has_value()) {
      observation.delivered.freshness = fold_worst_of(sum.freshness);
    }
    if (!filter.require_evidenced || observation.basis == ReserveBasis::Evidenced ||
        observation.basis == ReserveBasis::Mixed) {
      out.scopes.push_back(std::move(observation));
    }
  } else if (!filter.loop.has_value()) {
    for (const ThermalZone& zone : context.structure().zones()) {
      if (filter.zone.has_value() && zone.id != filter.zone.value()) {
        continue;
      }
      const SubjectRef scope(SubjectKind::Zone, rebind<StrongId>(zone.id));
      Maybe<Quantity> delivered;
      for (std::size_t i = 0; i < points.size(); ++i) {
        if (points[i].zone == zone.id && observations[i].flow.value.has_value()) {
          delivered = observations[i].flow.value;
          break;
        }
      }
      ReserveObservation observation =
          observe_scope(context, scope, {}, delivered, observations, points, filter);
      if (filter.require_evidenced && observation.basis != ReserveBasis::Evidenced &&
          observation.basis != ReserveBasis::Mixed) {
        continue;
      }
      out.scopes.push_back(std::move(observation));
    }
  }

  std::sort(out.scopes.begin(), out.scopes.end(),
            [](const ReserveObservation& a, const ReserveObservation& b) { return a.scope < b.scope; });

  std::vector<Freshness> parts;
  for (const ReserveObservation& observation : out.scopes) {
    parts.push_back(observation.freshness);
  }
  out.freshness = parts.empty() ? Freshness::Unknown : fold_worst_of(parts);
  return out;
}

